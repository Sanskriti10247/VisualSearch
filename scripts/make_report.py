#!/usr/bin/env python
"""Render results/*.json into docs/REPORT_TABLES.md and docs/figures/*.png.

Every number in the generated file comes straight from the results JSON, so the
report cannot drift from the measurements.
"""

from __future__ import annotations

import json
import re

from visualsearch.config import PROJECT_ROOT

RESULTS = PROJECT_ROOT / "results"
OUT = PROJECT_ROOT / "docs" / "REPORT_TABLES.md"
FIG = PROJECT_ROOT / "docs" / "figures"
METRIC = re.compile(r"(R@\d+|MRR|mAP|P@\d+|[Rr]ecall|Precision|Coverage|ECE|Brier|Task R@|"
                    r"Full results|AP|base rate)")
ORDER = ["models_text_image", "models_image_image", "preprocessing", "calibration",
         "hard_negatives", "hybrid", "rerank", "ann_benchmark", "filtered_search",
         "throughput", "query_latency"]


def fmt(v, col: str) -> str:
    if v is None:
        return "–"
    if isinstance(v, float):
        if METRIC.search(col) and 0 <= v <= 1 and not col.startswith(("ECE", "Brier", "base")):
            return f"{100 * v:.1f}"
        if col.startswith(("ECE", "Brier", "base")):
            return f"{v:.4f}"
        return f"{v:.3g}" if abs(v) < 1000 else f"{v:,.0f}"
    if isinstance(v, list) and len(v) == 2 and all(isinstance(x, float) for x in v):
        return f"[{100 * v[0]:.1f}, {100 * v[1]:.1f}]"
    return str(v).replace("|", "\\|")


def md_table(t: dict) -> str:
    cols = t["columns"]
    best = {}
    for c in t.get("highlight_best", []):
        vals = [r[c] for r in t["rows"] if isinstance(r[c], (int, float))]
        if vals:
            best[c] = max(vals)
    lines = [f"**{t['title']}**", "", "| " + " | ".join(cols) + " |",
             "|" + "|".join("---" for _ in cols) + "|"]
    for r in t["rows"]:
        cells = []
        for i, (v, c) in enumerate(zip(r, cols)):
            s = fmt(v, c)
            cells.append(f"**{s}**" if i in best and v == best[i] else s)
        lines.append("| " + " | ".join(cells) + " |")
    if t.get("notes"):
        lines += ["", f"_{t['notes']}_"]
    return "\n".join(lines)


def plot(ch: dict, path) -> bool:
    try:
        import matplotlib

        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return False
    fig, ax = plt.subplots(figsize=(6.4, 4))
    for s in ch["series"]:
        pts = sorted(s["points"]) if ch["type"] == "line" else s["points"]
        xs, ys = [p[0] for p in pts], [p[1] for p in pts]
        if ch["type"] == "scatter":
            ax.scatter(xs, ys, label=s["name"])
        else:
            ax.plot(xs, ys, marker="o", ms=3, label=s["name"])
    if ch.get("log_x"):
        ax.set_xscale("log")
    ax.set_xlabel(ch["x_label"])
    ax.set_ylabel(ch["y_label"])
    ax.set_title(ch["title"], fontsize=9)
    ax.grid(alpha=0.3)
    ax.legend(fontsize=7)
    fig.tight_layout()
    fig.savefig(path, dpi=130)
    plt.close(fig)
    return True


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    files = {p.stem: json.loads(p.read_text()) for p in RESULTS.glob("*.json")}
    names = [n for n in ORDER if n in files] + sorted(set(files) - set(ORDER))
    intro = ("_Auto-generated by `scripts/make_report.py` from `results/*.json`. Do not edit by "
             "hand. Metrics are percentages unless noted._")
    out = ["# Generated result tables", "", intro, ""]
    for name in names:
        res = files[name]
        rep = res.get("report")
        if not rep:
            continue
        env = res.get("environment", {})
        prov = (f"`results/{name}.json` · generated {res['generated_at']}"
                f" · commit {env.get('git_commit', '?')}{' (dirty)' if env.get('git_dirty') else ''}"
                f" · {env.get('gpu') or env.get('cpu', '')}")
        out += [f"## {rep['title']}", "", prov, "", rep.get("description", ""), ""]
        for t in rep.get("tables", []):
            out += [md_table(t), ""]
        for i, ch in enumerate(rep.get("charts", [])):
            fname = f"{name}_{i}.png"
            if plot(ch, FIG / fname):
                out += [f"![{ch['title']}](figures/{fname})", ""]
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
